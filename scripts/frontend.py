"""Deterministic frontend build: ordered native JS, CSS layers, and page templates.

Runtime keeps the existing three root assets. No Node packages or network are needed.
Use operate.py to run this command and supply the active TASK for build/watch writes.
"""
from __future__ import annotations
import argparse
from html.parser import HTMLParser
from html import escape
import importlib.util
import json
from pathlib import Path
import re
import sys
import time

ROOT=Path(__file__).resolve().parents[1]
class FrontendError(ValueError):
    pass

def source_path(web:Path,name:str)->Path:
    if not isinstance(name,str) or not name:
        raise FrontendError('source path must be a nonempty string')
    path=(web/name).resolve()
    if not path.is_relative_to(web.resolve()) or not path.is_file():
        raise FrontendError(f'missing or outside frontend source: {name}')
    return path

def read_json(web:Path,name:str):
    try:return json.loads(source_path(web,name).read_text(encoding='utf-8'))
    except json.JSONDecodeError as exc:raise FrontendError(f'invalid JSON: {name}: {exc.msg}') from exc

def expand_template(web:Path,name:str,stack:tuple[str,...]=())->str:
    if name in stack:raise FrontendError('template include cycle: '+' -> '.join((*stack,name)))
    content=source_path(web,name).read_text(encoding='utf-8')
    return re.sub(r'<!--\s*@include\s+([^\s]+)\s*-->',lambda match:expand_template(web,match[1],(*stack,name)).rstrip(),content)

class MarkupContract(HTMLParser):
    def __init__(self):
        super().__init__();self.ids=set();self.pages=set();self.primary_tabs=set()
    def handle_starttag(self,tag,attrs):
        attrs=dict(attrs)
        if attrs.get('id'):
            if attrs['id'] in self.ids:raise FrontendError('duplicate HTML id: '+attrs['id'])
            self.ids.add(attrs['id'])
        if tag=='section' and 'page' in attrs.get('class','').split():self.pages.add(attrs.get('id'))
        if 'data-tab' in attrs:self.primary_tabs.add(attrs['data-tab'])

def render_assets(root:Path=ROOT)->dict[str,str]:
    web=root/'web';manifest=read_json(web,'frontend.json')
    if manifest.get('schema_version')!=1:raise FrontendError('unsupported frontend manifest schema')
    routes=read_json(web,manifest['routes'])
    if routes.get('schema_version')!=1:raise FrontendError('unsupported route schema')
    pages=routes.get('pages',[]);ids=[page['id'] for page in pages]
    if len(ids)!=len(set(ids)):raise FrontendError('duplicate page route')
    for page in pages:source_path(web,page['template'])
    scripts=manifest.get('scripts',[]);styles=manifest.get('styles',[])
    if len(scripts)!=len(set(scripts)) or len(styles)!=len(set(styles)):raise FrontendError('duplicate source in build manifest')
    if scripts.count('@routes')!=1:raise FrontendError('exactly one @routes module is required')
    js=[]
    for name in scripts:
        if name=='@routes':body='const ROUTE_DEFINITIONS='+json.dumps(routes,ensure_ascii=False,separators=(',',':'))+';\n'
        else:
            if not name.endswith('.js'):raise FrontendError('script must be .js: '+name)
            body=source_path(web,name).read_text(encoding='utf-8')
        js.append('// Source: '+name+'\n'+body.rstrip()+'\n')
    css=[]
    for name in styles:
        if not name.endswith('.css'):raise FrontendError('style must be .css: '+name)
        css.append('/* Source: '+name+' */\n'+source_path(web,name).read_text(encoding='utf-8').rstrip()+'\n')
    html=expand_template(web,manifest['shell']).rstrip()+'\n'
    contract=MarkupContract();contract.feed(html)
    if contract.pages!=set(ids):raise FrontendError('page templates and route registry disagree')
    if contract.primary_tabs!={page['id'] for page in pages if page.get('primary')}:raise FrontendError('primary navigation and route registry disagree')
    if any(name in contract.ids for name in ['page-breadcrumb','breadcrumb']):raise FrontendError('breadcrumb is not part of this application')
    names=manifest.get('outputs',{})
    if names!={'html':'index.html','js':'app.js','css':'style.css'}:raise FrontendError('runtime output names must preserve the static service contract')
    banner='Generated by scripts/frontend.py. Edit web/src, web/styles, web/routes.json or web/frontend.json.'
    return {'index.html':html,'app.js':'/* '+banner+' */\n'+''.join(js),'style.css':'/* '+banner+' */\n'+''.join(css)}

def differences(root:Path,assets:dict[str,str])->list[str]:
    drift=[]
    for name,content in assets.items():
        for folder in [root/'web',root/'flavoretro/assets/web']:
            path=folder/name
            if not path.is_file() or path.read_bytes()!=content.encode('utf-8'):drift.append(str(path.relative_to(root)))
    return drift

def build(root:Path,task:str)->int:
    if not task:raise FrontendError('build/watch requires --task TASK-NNN for the operation journal')
    if root.resolve()!=ROOT:raise FrontendError('CLI writes only to this project')
    assets=render_assets(root)
    spec=importlib.util.spec_from_file_location('frontend_operate',root/'scripts/operate.py');operate=importlib.util.module_from_spec(spec);spec.loader.exec_module(operate)
    changed=0
    for name,content in assets.items():
        for folder in ['web','flavoretro/assets/web']:
            path=f'{folder}/{name}'
            if not (root/path).is_file() or (root/path).read_bytes()!=content.encode('utf-8'):
                operate.write(task,path,content);changed+=1
    return changed


def scaffold_plan(root:Path,page_id:str,title:str)->dict[str,str]:
    """Return source edits for a page; no files are written until the approved command applies them."""
    if not re.fullmatch(r'[a-z][a-z0-9-]{0,39}',page_id or ''):raise FrontendError('page id must be a lowercase slug, up to 40 characters')
    if not title or not title.strip():raise FrontendError('page title is required')
    render_assets(root)  # Reject an invalid baseline before planning any source writes.
    web=root/'web';manifest=read_json(web,'frontend.json');routes=read_json(web,manifest['routes'])
    if page_id in {page['id'] for page in routes['pages']}:raise FrontendError('page already exists: '+page_id)
    template=f'src/pages/{page_id}/view.html';controller=f'src/pages/{page_id}/controller.js'
    if (web/template).exists() or (web/controller).exists():raise FrontendError('scaffold would overwrite existing source')
    view=f'<section id="{page_id}" class="page" hidden role="region" aria-labelledby="{page_id}-title">\n    <div class="page-heading"><h1 id="{page_id}-title">{escape(title.strip())}</h1></div>\n    <section class="ui-panel"><div id="{page_id}-content"></div></section>\n</section>\n'
    script=f"PageRegistry.register({json.dumps(page_id)},()=>{{\n    const target=UI.byId({json.dumps(page_id+'-content')});\n    if(!target.children.length)target.append(UI.empty('暂无内容。'));\n}});\n"
    routes['pages'].append({'id':page_id,'title':title.strip(),'template':template,'primary':False})
    routes['subpages'].append({'path':'#/'+page_id,'state':[],'purpose':title.strip()})
    manifest['scripts'].insert(manifest['scripts'].index('src/core/router.js'),controller)
    shell=source_path(web,manifest['shell']).read_text(encoding='utf-8')
    if shell.count('</main>')!=1:raise FrontendError('shell must contain one main closing tag')
    shell=shell.replace('</main>',f'    <!-- @include {template} -->\n    </main>')
    return {template:view,controller:script,manifest['routes']:json.dumps(routes,ensure_ascii=False,indent=2)+'\n','frontend.json':json.dumps(manifest,ensure_ascii=False,indent=2)+'\n',manifest['shell']:shell}

def apply_scaffold(root:Path,task:str,page_id:str,title:str)->int:
    if not task:raise FrontendError('create-page requires --task TASK-NNN')
    if root.resolve()!=ROOT:raise FrontendError('CLI writes only to this project')
    plan=scaffold_plan(root,page_id,title)
    spec=importlib.util.spec_from_file_location('frontend_operate',root/'scripts/operate.py');operate=importlib.util.module_from_spec(spec);spec.loader.exec_module(operate)
    for name,content in plan.items():operate.write(task,'web/'+name,content)
    return len(plan)+build(root,task)

def main(argv=None)->int:
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('command',nargs='?',choices=['build','check','watch','routes','create-page'],default='check')
    parser.add_argument('--id',help='new page slug for create-page')
    parser.add_argument('--title',help='new page title for create-page')
    parser.add_argument('--check',action='store_true',help='alias for check')
    parser.add_argument('--task',help='active task journal label for build/watch')
    parser.add_argument('--interval',type=float,default=1.0,help='watch interval, seconds')
    args=parser.parse_args(argv);command='check' if args.check else args.command
    try:
        if command=='create-page':
            count=apply_scaffold(ROOT,args.task,args.id,args.title);print(f'Page #{args.id} created; {count} source/output files updated.')
        elif command=='routes':
            routes=read_json(ROOT/'web','routes.json')
            for route in routes['subpages']:print(route['path']+'  '+route['purpose'])
        elif command=='check':
            drift=differences(ROOT,render_assets(ROOT))
            if drift:
                print('Frontend outputs are stale: '+', '.join(drift),file=sys.stderr);return 1
            print('Frontend sources, page routes, runtime assets and package mirrors match.')
        elif command=='build':print(f'Frontend built; {build(ROOT,args.task)} files updated.')
        else:
            if not args.task:raise FrontendError('watch requires --task TASK-NNN')
            if args.interval<0.1:raise FrontendError('watch interval must be at least 0.1 seconds')
            print('Watching frontend sources; refresh the browser after a build.',flush=True)
            last_error=None
            while True:
                try:
                    changed=build(ROOT,args.task)
                    if changed:print(f'Frontend built; {changed} files updated.',flush=True)
                    last_error=None
                except (FrontendError,KeyError,OSError) as exc:
                    message=str(exc)
                    if message!=last_error:print(message,file=sys.stderr,flush=True);last_error=message
                time.sleep(args.interval)
    except (FrontendError,KeyError,OSError) as exc:
        print('Frontend error: '+str(exc),file=sys.stderr);return 1
    except KeyboardInterrupt:return 0
    return 0

if __name__=='__main__':raise SystemExit(main())
